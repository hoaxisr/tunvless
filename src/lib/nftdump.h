/* nf_tables по netlink — ЧТЕНИЕ: счётчики и комментарии правил, число элементов набора, наличие
 * таблицы и цепочки, текст набора правил. То, что status и diag раньше узнавали запуском `nft`.
 *
 * ЗАЧЕМ. `steer status` интерфейс опрашивает раз в несколько секунд, и каждый вызов стоил двух
 * `sh -c nft …` — около семи процессов (счётчики четырёх цепочек и дамп ruleset для fw_check);
 * diag — около двадцати. Принцип владельца (docs/architecture.md, раздел 2): пользовательский
 * процесс — только там, где без него нельзя. Вопросы здесь те же, что задавал `nft`, и ядро
 * отвечает на них тем же сообщением NFT_MSG_GET*, только без fork, exec и разбора текста.
 *
 * ПИСАТЬ — НЕ ЗДЕСЬ. Транзакции (элементы наборов от резолвера) живут в nftnl.c со своим
 * долгоживущим сокетом; этот файл сокет открывает на вызов и ничего в ядре не меняет. Разделены
 * они потому, что nftnl.c — библиотека резолвера со своими глобалами (таблица, раскладка
 * интервалов), а читателям — демону, status, diag, kinds — ни то ни другое не нужно.
 *
 * СТАРОЕ ЯДРО. Фильтр дампа правил по таблице и цепочке ядро понимает не всегда (на 4.9 его нет),
 * поэтому отбор повторяется здесь по атрибутам ответа. Одиночный запрос элемента на 4.9 не
 * работает — число элементов считается дампом, и он работает везде.
 *
 * Синхронно: ядро отвечает на запрос внутри того же системного вызова. Зовёт только основной
 * поток. */
#ifndef STEER_NFTDUMP_H
#define STEER_NFTDUMP_H

#include <stdint.h>
#include <stddef.h>

/* Семейства — числа NFPROTO_* (linux/netfilter.h): inet 1, ip 2, ip6 10. */
#define NFD_INET 1
#define NFD_IP   2

/* Правила перечисленных цепочек таблицы по одному, одним дампом: комментарий (userdata, как его
 * пишет nft; "" — нет), счётчик (has_counter 0 — выражения counter в правиле нет). 0 — таблицу
 * прочитали (в том числе без этих цепочек или без самой таблицы: nft о них тоже молчит), иначе
 * errno. */
typedef void (*nfd_rule_fn)(void *arg, const char *comment, int has_counter,
                            uint64_t packets, uint64_t bytes);
int nfd_chain_rules(uint8_t family, const char *table, const char *const *chains, size_t n,
                    nfd_rule_fn fn, void *arg);

/* Сколько элементов в наборе — столько, сколько их напечатал бы `nft list set`: у интервального
 * набора диапазон — один элемент (конец диапазона ядро хранит отдельной записью, она не в счёт).
 * -1 — набора нет или ядро не ответило. */
long nfd_set_count(uint8_t family, const char *table, const char *set);

/* Есть ли таблица; есть ли цепочка в таблице. 1 — есть, 0 — нет или ядро не ответило. */
int nfd_table_exists(uint8_t family, const char *table);
int nfd_chain_exists(uint8_t family, const char *table, const char *chain);

/* Есть ли в таблице правило `redirect to :PORT` (выражение redir с портом из immediate).
 * 1 — есть, 0 — нет. */
int nfd_has_redirect(uint8_t family, const char *table, uint16_t port);

/* Весь набор правил текстом в форме `nft -t list ruleset` — в объёме того, что читает fw_check
 * (src/daemon/fwcheck.c): заголовки таблиц, наборов, flowtable и цепочек (с устройствами хуков),
 * а в правилах — имена устройств (iifname/oifname/iif/oif, в том числе в безымянных наборах и
 * картах вердиктов), состояние и статус ct, переходы и вердикты, masquerade/snat/dnat/redirect,
 * префикс log и комментарии. Прочие выражения (адреса, порты, метки) не печатаются: проверка их
 * не читает, а печать заново повторяла бы nft целиком. Строка malloc'ом; NULL — ядро не ответило
 * или нет памяти. */
char *nfd_ruleset_text(void);

#endif
