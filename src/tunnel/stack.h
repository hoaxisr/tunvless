/* Стек туннеля: пакеты из TUN в потоки к узлу через дайлер (dialer.h). Границы — в stack.c. */
#ifndef STEER_STACK_H
#define STEER_STACK_H
#include "dialer.h"
/* Нужен struct output: туннель привязывает таблицу к своему устройству сам, а метка и
 * таблица живут в выходе. Объявления вперёд здесь недостаточно — поля читаются. */
#include "spec.h"

/* Поднять TUN выхода и нести через него трафик дайлером d, пока не кончатся очереди.
 *
 * Выход передаётся целиком, а не именем устройства: туннель сам поднимает устройство,
 * сам даёт ему адрес и сам привязывает к нему таблицу маршрутизации — а для этого нужны
 * и метка, и таблица из реестра. Никто снаружи не знает момент, когда TUN готов.
 *
 * Возвращает всегда 1: успешного выхода у цикла нет (см. конец stack_run). */
int stack_run(struct output *o, const struct dialer *d);

/* Поднять устройство и дать ему адрес из таблицы выхода. Каждый отказ `ip` называется в
 * журнале своим тоном (I-114). Отдельно от stack_run — ради стенда devupmatch. */
void tun_bring_up(const char *dev, int table);

#endif
